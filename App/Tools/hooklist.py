#!/usr/bin/env python3
"""Writes Sources/Chains/EVM/UniswapV4Hooks.swift: the Uniswap v4 hooks a swap this app signs may run, from Uniswap's own
hook registry (github.com/Uniswap/hooklist), pinned to one commit so the list only changes when this script is run again.

A hook is kept when the registry says that once a swap is allowed it goes exactly as in a pool without hooks
(vanillaSwap: no dynamic fee, no delta taken from the amounts, no custom swap data, no nested swap or transfer), its
source is verified, it can't be upgraded, nothing gates who may swap, and its address asks for no swap delta.

Run from App/:  python3 Tools/hooklist.py [<commit>]   (no commit: the registry's latest)
"""
import json
import subprocess
import sys
import urllib.request

CHAINS = {"base": 8453, "arbitrum": 42161, "ethereum": 1, "polygon": 137, "robinhood": 4663}
OUT = "Sources/Chains/EVM/UniswapV4Hooks.swift"


def latest():
    out = subprocess.run(["gh", "api", "repos/Uniswap/hooklist/commits/main", "--jq", ".sha + \" \" + .commit.committer.date"],
                         capture_output=True, text=True, check=True).stdout.split()
    return out[0], out[1][:10]


def main():
    sha, date = (sys.argv[1], "") if len(sys.argv) > 1 else latest()
    url = f"https://raw.githubusercontent.com/Uniswap/hooklist/{sha}/hooklist.json"
    hooks = json.load(urllib.request.urlopen(url, timeout=60))
    keep = {chain: set() for chain in CHAINS.values()}
    for h in hooks:
        chain = CHAINS.get(h["hook"]["chain"])
        p, f = h["properties"], h["flags"]
        address = h["hook"]["address"].lower()
        bits = int(address[-4:], 16) & 0x3FFF
        if chain is None or chain != h["hook"]["chainId"]:
            continue
        if (h["hook"]["verifiedSource"] and p["vanillaSwap"] and not p["upgradeable"] and not p["requiresCustomSwapData"]
                and not p["dynamicFee"] and p["swapAccess"] == "none" and not f["beforeSwapReturnsDelta"]
                and not f["afterSwapReturnsDelta"] and bits & 0b1100 == 0):
            keep[chain].add(address)
    lines = [
        f"// Generated by Tools/hooklist.py from github.com/Uniswap/hooklist at {sha}{f' ({date})' if date else ''}.",
        "// Don't edit by hand: run the script again to refresh it.",
        "",
        "extension UniswapV4 {",
        "    /// Per network, the hooks Uniswap's registry marks as a vanilla swap with verified source, not upgradeable, needing",
        "    /// no custom data and gating nobody (Tools/hooklist.py says how they're chosen).",
        "    static let vanillaHooks: [UInt64: Set<String>] = [",
    ]
    for chain in CHAINS.values():
        lines.append(f"        {chain}: [")
        lines += [f'            "{a}",' for a in sorted(keep[chain])]
        lines.append("        ],")
    lines += ["    ]", "}", ""]
    open(OUT, "w").write("\n".join(lines))
    print(f"{OUT}: " + ", ".join(f"{name} {len(keep[chain])}" for name, chain in CHAINS.items()) + f" (hooklist {sha[:7]})")


if __name__ == "__main__":
    main()
